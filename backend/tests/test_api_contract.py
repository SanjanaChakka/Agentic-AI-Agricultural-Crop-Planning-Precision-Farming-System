def test_safety_contract_states_that_nothing_is_actuated(client: TestClient) -> None:
    payload = client.get(f"{API}/approvals/safety-contract").json()

    blob = " ".join(str(value) for value in payload.values()).lower()
    assert "approval" in blob
    assert any(word in blob for word in ("no code path", "documentation", "never"))


