def test_model_cards_publish_target_and_training_metadata(client: TestClient) -> None:
    cards = client.get(f"{API}/ml/models").json()

    assert cards, "the model registry must publish model cards"
    for card in cards:
        if card.get("available"):
            assert card.get("target"), "a prediction must declare what it predicts"
            assert card.get("trained_at"), "a prediction must declare when the model was trained"
            assert card.get("model_version")


def test_settings_never_publish_a_secret(client: TestClient) -> None:
    schema = client.get("/openapi.json").json()
    rendered = repr(schema).lower()

    for marker in ('api_key":', 'password":', 'secret":', 'private_key":'):
        assert marker not in rendered, f"the schema appears to expose {marker}"


